#!/usr/bin/env python3
"""Emit the LaTeX tables and in-text numbers of the paper from the v2 data.

Input : ../data/all-trials.csv            (247 rows; only valid trials are used)
        ../data/summary-by-condition.csv  (per-cell precision check)
        ../data/bluegreen-tick-delay.csv  (abort ticks of the analysis-detected blue-green trials)
Output: OUT_DIR/{breakdown,impact,coverage}.tex  (tables)
        OUT_DIR/numbers.tex                      (\\newcommand macros, prefix \\m)

Needs pandas (runner/requirements.txt). RESULTS_DIR overrides the input directory,
OUT_DIR the output directory (default: ./out next to this script).
"""
import math
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
RES = os.path.expanduser(os.environ.get("RESULTS_DIR", os.path.join(PAPER, "data")))
OUT = os.path.expanduser(os.environ.get("OUT_DIR", os.path.join(HERE, "out")))

STRATS = ["canary", "bluegreen", "rolling"]
SNAME = {"canary": "Canary", "bluegreen": "Blue-green", "rolling": "Rolling"}
SHORT = {"canary": "C", "bluegreen": "B", "rolling": "R"}
CORE = ["faulty-release", "network-partition", "crashloop", "bad-image"]
SCEN = {"faulty-release": "Faulty release", "network-partition": "Dep.\\ partition",
        "crashloop": "Crash loop", "bad-image": "Bad image"}
RELEASE_FAULTS = ["faulty-release", "network-partition", "crashloop"]
KEY = {"faulty-release": "Faulty", "network-partition": "Part", "crashloop": "Crash", "bad-image": "Bad"}


def f1(x, fmt="{:.1f}"):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return fmt.format(x)


def wilson(k, n, z=1.959964):
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h) / d, (c + h) / d


def write(name, text):
    with open(os.path.join(OUT, name), "w") as f:
        f.write("% generated by scripts/make_tables.py from v2/results/main -- do not edit\n")
        f.write(text)


def table(name, caption, label, spec, head, lines, size="\\footnotesize", sep="2.6pt"):
    write(name, "\\begin{table}[t]\n\\caption{%s}\n\\label{%s}\n\\centering\n%s\n"
          "\\setlength{\\tabcolsep}{%s}\n\\begin{tabular}{@{}%s@{}}\n\\toprule\n%s \\\\\n\\midrule\n%s\n"
          "\\bottomrule\n\\end{tabular}\n\\end{table}\n" % (caption, label, size, sep, spec, head, "\n".join(lines)))


def main():
    os.makedirs(OUT, exist_ok=True)
    allrows = pd.read_csv(os.path.join(RES, "all-trials.csv"))
    v = allrows[allrows.valid.astype(str) == "True"].copy()
    N = {}

    def put(name, x, fmt="{:.1f}"):
        N[name] = x if isinstance(x, str) else f1(float(x), fmt) if fmt != "{:d}" else "%d" % x

    def cell(s, k=None, **kw):
        g = v[v.scenario == s]
        if k:
            g = g[g.strategy == k]
        for a, b in kw.items():
            g = g[g[a] == b]
        return g

    # ---------- data set ------------------------------------------------------
    inv = allrows[allrows.valid.astype(str) != "True"]
    put("NRows", len(allrows), "{:d}")
    put("NValid", len(v), "{:d}")
    put("NInvalid", len(inv), "{:d}")
    put("NInvalidHistory", int((inv.scenario == "bad-image-after-abort").sum()), "{:d}")
    put("NReruns", int(allrows.trial_id.str.endswith("r1").sum()), "{:d}")
    cells = v.groupby(["scenario", "strategy", "sync_policy", "revert_path"]).size()
    put("NCellsSeven", int((cells == 7).sum()), "{:d}")

    summ = pd.read_csv(os.path.join(RES, "summary-by-condition.csv"))
    pm = summ[summ["precision met"].astype(str).isin(["True", "False"])]
    put("NPrecMet", int((pm["precision met"].astype(str) == "True").sum()), "{:d}")
    put("NPrecCells", len(pm), "{:d}")
    hw = summ.set_index(["scenario", "strategy", "sync", "revert"])["CI half-width"]
    put("PollHalfWidth", float(hw[("faulty-release", "canary", "auto", "poll")]))

    trig = v[v.rollback_triggered.astype(str) == "True"]
    put("NRollbacks", len(trig), "{:d}")
    put("NAnalysis", int((trig.trigger_cause == "analysis").sum()), "{:d}")
    put("NDeadline", int((trig.trigger_cause == "deadline").sum()), "{:d}")
    ok = int(trig.rollback_success.astype(str).eq("True").sum())
    put("NRollbackOK", ok, "{:d}")
    put("SuccessCILo", wilson(ok, len(trig))[0], "{:.2f}")
    sdg = v[v.argocd_state_before_revert == "Synced/Degraded"]
    put("NSyncedDegraded", len(sdg), "{:d}")
    put("NSyncsBeforeRevert", int(sdg.argocd_syncs_between_abort_and_revert.sum()), "{:d}")

    core = v[v.scenario.isin(CORE) & (v.sync_policy == "auto") & (v.revert_path == "webhook")]

    # ---------- Table: breakdown (core pooled over strategies; revert path) ---
    comps = ["comp_detection_s", "comp_rollback_s", "comp_operator_wait_s", "comp_reconcile_s"]

    def brow(label, g, cause):
        return "%s (%s) & %s & %s & %s & %s & %s & %s & %s \\\\" % (
            label, cause, *(f1(g[c].mean()) for c in comps), f1(g.mttr_service_s.mean()),
            f1(g.mttr_full_s.mean()), f1(g.mttr_full_s.std()))

    lines = []
    for s in CORE:
        g = core[core.scenario == s]
        lines.append(brow(SCEN[s], g, "A" if g.trigger_cause.iloc[0] == "analysis" else "D"))
    lines.append("\\midrule\n\\multicolumn{8}{@{}l}{\\emph{Revert path} (canary, faulty release)} \\\\")
    web = cell("faulty-release", "canary", sync_policy="auto", revert_path="webhook")
    poll = cell("faulty-release", "canary", revert_path="poll")
    man = cell("faulty-release", "canary", sync_policy="manual")
    for lab, g in [("Webhook", web), ("Polling", poll), ("Manual sync", man)]:
        lines.append(brow("\\quad " + lab, g, "A"))
    table("breakdown.tex",
          "Mean recovery components in seconds. Core rows pool the three strategies (21 trials; automated sync, "
          "webhook); revert-path rows have 7. Detected by A = analysis, D = deadline (configured, 90\\,s); "
          "operator wait configured (45\\,s). Detection runs from the release reaching the cluster for Git "
          "faults and from fault activation for chaos faults. Components overlap; SD$_{\\mathrm{f}}$ = SD of $\\mathrm{MTTR}_{\\mathrm{f}}$.",
          "tab:breakdown", "lrrrrrrr",
          "Scenario & Det. & Rollb. & Op. & Recon. & $\\mathrm{MTTR}_{\\mathrm{s}}$ & "
          "$\\mathrm{MTTR}_{\\mathrm{f}}$ & SD$_{\\mathrm{f}}$", lines, sep="2.0pt")

    for key, c in [("Det", "comp_detection_s"), ("Op", "comp_operator_wait_s"), ("Rec", "comp_reconcile_s")]:
        sh = core.assign(x=core[c] / core.mttr_full_s * 100).groupby("scenario").x.mean()
        put("Share%sLo" % key, sh.min(), "{:.0f}")
        put("Share%sHi" % key, sh.max(), "{:.0f}")
    dm = core.groupby("scenario").comp_detection_s.mean()
    put("DetCoreLo", dm.min())
    put("DetCoreHi", dm.max())
    put("OosLag", core.outofsync_lag_s.mean())
    put("SyncDur", core.sync_duration_s.mean())
    put("ReconCore", core.comp_reconcile_s.mean())
    put("OpWaitLo", v.comp_operator_wait_s.min())
    put("OpWaitHi", v.comp_operator_wait_s.max())
    rb = trig.groupby("strategy").rollback_execution_s
    put("RollbackRollingMean", rb.mean()["rolling"])
    put("RollbackRollingMax", rb.max()["rolling"])
    put("RollbackCanaryMax", rb.max()["canary"])

    # ---------- H1a: strategy range of MTTR_full condition means ---------------
    means = core.groupby(["scenario", "strategy"]).mttr_full_s.mean().unstack()
    rng = means.max(axis=1) - means.min(axis=1)
    for s in CORE:
        put("Range%s" % KEY[s], rng[s])
    put("RangeMax", rng.max())

    # ---------- Table: user impact by strategy ---------------------------------
    lines = []
    for s in RELEASE_FAULTS:
        for i, k in enumerate(STRATS):
            g = core[(core.scenario == s) & (core.strategy == k)]
            lines.append("%s & %s & %s & %s\\,(%s) & %s & %s & %s \\\\" % (
                ("\\multirow{3}{*}{%s}" % SCEN[s]) if i == 0 else "", SNAME[k],
                f1(g.first_fault_response_s.median()) if s != "crashloop" else "--",
                f1(g.mttr_service_s.mean()), f1(g.mttr_service_s.std()), f1(g.failed_requests.mean()),
                f1(g.requests_served_by_release.mean(), "{:.0f}"), f1(g.mttr_full_s.mean())))
        if s != RELEASE_FAULTS[-1]:
            lines.append("\\midrule")
    table("impact.tex",
          "User impact by strategy, faults in the new release (7 trials per row): median first faulty "
          "response $t_e$, mean (SD) $\\mathrm{MTTR}_{\\mathrm{s}}$ and mean $\\mathrm{MTTR}_{\\mathrm{f}}$ "
          "in seconds; per-trial mean failed requests and requests served by the faulty release "
          "(blue-green 0: no faulty preview promoted).",
          "tab:impact", "llrrrrr",
          "Scenario & Strategy & $t_e$ & $\\mathrm{MTTR}_{\\mathrm{s}}$ & Failed & Served & "
          "$\\mathrm{MTTR}_{\\mathrm{f}}$", lines, sep="2.4pt")

    for s in RELEASE_FAULTS:
        for k in STRATS:
            g = core[(core.scenario == s) & (core.strategy == k)]
            put("Fail%s%s" % (KEY[s], SHORT[k]), g.failed_requests.mean())
            put("Te%s%s" % (KEY[s], SHORT[k]), g.first_fault_response_s.median())
            x = g.rollback_trigger_latency_s
            put("Late%s%s" % (KEY[s], SHORT[k]), int((x > x.min() + 7.5).sum()), "{:d}")
    bg = v[(v.strategy == "bluegreen") & v.trigger_cause.isin(["analysis", "deadline"])
           & ~v.scenario.str.startswith("config")]
    put("NBGRelease", len(bg), "{:d}")
    put("NBGZero", int(((bg.mttr_service_s == 0) & (bg.failed_requests == 0)).sum()), "{:d}")
    cl = core[core.scenario == "crashloop"].rollback_trigger_latency_s
    put("CrashEarlyLo", cl[cl < 12].min())
    put("CrashEarlyHi", cl[cl < 12].max())
    put("CrashLateLo", cl[cl >= 12].min())
    put("CrashLateHi", cl[cl >= 12].max())
    put("NCrashLate", int((cl >= 12).sum()), "{:d}")
    dl = trig[trig.trigger_cause == "deadline"].rollback_trigger_latency_s
    put("DeadlineLo", dl.min())
    put("DeadlineHi", dl.max())
    put("NDeadlineIn", int(((dl - 90).abs() <= 3).sum()), "{:d}")

    # ---------- analysis-detected blue-green trials --------------------------
    put("NModelBG", int(((trig.strategy == "bluegreen") & (trig.trigger_cause == "analysis")).sum()), "{:d}")
    bg = pd.read_csv(os.path.join(RES, "bluegreen-tick-delay.csv"))
    assert len(bg) == int(N["NModelBG"])
    put("NBGEarly", int(bg.delayed_one_tick.astype(str).eq("True").sum()), "{:d}")

    # ---------- Table: coverage and recovery outside the core ------------------
    def cls(g):
        c = g.coverage_class.astype(str)
        if c.str.contains("/").any():   # drift under manual sync: the layer that recovered decides
            a = int((g.recovered_by == "rollouts").sum())
            return "analysis %d, operator %d" % (a, len(g) - a)
        name = {"operator-only": "operator"}
        out = ", ".join("%s %d" % (name.get(x, x), n) for x, n in c.value_counts().items())
        fr = int(((c == "tolerated") & g.recovered_by.astype(str).str.contains("operator")).sum())
        return out + (" (%d false revert)" % fr if fr else "")

    def crow(label, g, strat):
        full = "cens." if g.censored.astype(str).eq("True").all() else f1(g.mttr_full_s.mean())
        return "%s & %s & %s & %s & %s \\\\" % (label, strat, cls(g), f1(g.mttr_service_s.mean()), full)

    lines = []
    for lab, g in [("Drift, auto", v[(v.scenario == "config-drift") & (v.sync_policy == "auto")]),
                   ("Drift, manual", v[(v.scenario == "config-drift") & (v.sync_policy == "manual")]),
                   ("Prom.\\ 120\\,s, faulty", cell("cp-rollouts-prometheus-faulty")),
                   ("Prom.\\ 300\\,s, faulty", cell("cp-rollouts-prometheus-faulty-long")),
                   ("History", cell("bad-image-after-abort"))]:
        for i, k in enumerate(STRATS):
            gk = g[g.strategy == k]
            nrow = sum(len(g[g.strategy == x]) > 0 for x in STRATS)
            first = ("\\multirow{%d}{*}{%s}" % (nrow, lab)) if i == 0 else ""
            if len(gk) == 0:
                continue  # rolling history: precondition never reached (stated in the text and caption)
            else:
                lines.append(crow(first, gk, SHORT[k]))
        lines.append("\\midrule")
    for lab, s in [("Prom.\\ 120\\,s, healthy", "cp-rollouts-prometheus-healthy"),
                   ("Prom.\\ 300\\,s, healthy", "cp-rollouts-prometheus-healthy-long"),
                   ("Argo CD--Gitea", "cp-argocd-gitea-revert")]:
        # K1/K2 stable-pod controls dropped from the paper (decision D3)
        lines.append(crow(lab, cell(s), "C"))
    table("coverage.tex",
          "Detection coverage and recovery outside the core (7 valid trials per row; C/B/R = canary, "
          "blue-green, rolling): class counts, mean $\\mathrm{MTTR}_{\\mathrm{service}}$ and "
          "$\\mathrm{MTTR}_{\\mathrm{full}}$ in seconds; cens.\\ = every trial censored at 300\\,s; "
          "rolling never reached the history precondition.",
          "tab:coverage", "lllrr",
          "Cell & & Class (trials) & $\\mathrm{MTTR}_{\\mathrm{s}}$ & $\\mathrm{MTTR}_{\\mathrm{f}}$",
          lines, size="\\footnotesize", sep="2.4pt")

    # ---------- revert path (H4) -----------------------------------------------
    put("ManualDelta", man.mttr_full_s.mean() - web.mttr_full_s.mean())
    put("ManualFull", man.mttr_full_s.mean())
    put("WebFull", web.mttr_full_s.mean())
    put("PollFull", poll.mttr_full_s.mean())
    put("PollLagLo", poll.outofsync_lag_s.min())
    put("PollLagHi", poll.outofsync_lag_s.max())
    put("NPollOver", int((poll.outofsync_lag_s > 180).sum()), "{:d}")

    # ---------- control path and history (H3) ----------------------------------
    for s, nm in [("cp-rollouts-prometheus-faulty", "CPShort"), ("cp-rollouts-prometheus-faulty-long", "CPLong")]:
        for k in STRATS:
            g = cell(s, k)
            put("%sFull%s" % (nm, SHORT[k]), g.mttr_full_s.mean())
            put("%sSvc%s" % (nm, SHORT[k]), g.mttr_service_s.mean())
            put("%sFail%s" % (nm, SHORT[k]), g.failed_requests.mean(), "{:.0f}")
            put("%sDet%s" % (nm, SHORT[k]), g.rollback_trigger_latency_s.mean())
    gt = cell("cp-argocd-gitea-revert")
    put("GiteaSvc", gt.mttr_service_s.mean())
    put("GiteaFull", gt.mttr_full_s.mean())
    put("GiteaFullSD", gt.mttr_full_s.std())
    put("GiteaOos", gt.outofsync_lag_s.mean())
    h = cell("cp-rollouts-prometheus-healthy")
    put("HealthyMedian", h.mttr_full_s.median())
    put("HealthyMax", h.mttr_full_s.max())
    put("HealthyLong", cell("cp-rollouts-prometheus-healthy-long").mttr_full_s.mean())
    hist = cell("bad-image-after-abort")
    put("NHistoryCensored", int(hist.censored.astype(str).eq("True").sum()), "{:d}")

    # ---------- drift and controls ----------------------------------------------
    da = v[(v.scenario == "config-drift") & (v.sync_policy == "auto")]
    dmn = v[(v.scenario == "config-drift") & (v.sync_policy == "manual")]
    put("DriftAutoLo", da.groupby("strategy").mttr_full_s.mean().min())
    put("DriftAutoHi", da.groupby("strategy").mttr_full_s.mean().max())
    dbg = da[da.strategy == "bluegreen"]
    put("DriftStrictLo", dbg.mttr_full_strict_s.min())
    put("DriftStrictHi", dbg.mttr_full_strict_s.max())
    dca = da[da.strategy == "canary"]
    put("NDriftStrictCanary", int((dca.mttr_full_strict_s > 20).sum()), "{:d}")
    put("NDriftManAnalysis", int((dmn.recovered_by == "rollouts").sum()), "{:d}")
    put("NDriftMan", len(dmn), "{:d}")
    put("DriftManLo", dmn.groupby("strategy").mttr_full_s.mean().min())
    put("DriftManHi", dmn.groupby("strategy").mttr_full_s.mean().max())
    k1 = cell("control-stable-crash")
    put("KOneMean", k1.mttr_full_s.mean())
    put("KOneLo", k1.mttr_full_s.min())
    put("KOneHi", k1.mttr_full_s.max())
    put("KTwoSvc", cell("control-stable-partition").mttr_service_s.mean())

    # ---------- Prometheus vs object status ---------------------------------
    xa = trig.xcheck_abort_delta_s.dropna()
    put("PromAbortN", len(xa), "{:d}")
    put("PromAbortLo", xa.min())
    put("PromAbortHi", xa.max())
    put("PromAbortMedian", xa.median())
    oos = v[v.t_outofsync.notna()]
    for p, nm in [("auto", "Auto"), ("manual", "Manual")]:
        g = oos[oos.sync_policy == p]
        put("PromOos%s" % nm, int(g.prom_t_outofsync.notna().sum()), "{:d}")
        put("NOos%s" % nm, len(g), "{:d}")
    ga = oos[oos.sync_policy == "auto"]
    put("OosAutoMax", (ga.t_synced - ga.t_outofsync).max())  # automated sync clears OutOfSync within this

    # ---------- numbers quoted in the text --------------------------------------
    put("NBaselineInvalid", int((inv.baseline_success.astype(float) < 0.995).sum()), "{:d}")
    bgr = v[(v.strategy == "bluegreen") & v.scenario.isin(RELEASE_FAULTS)]
    put("BGSvcMax", bgr.mttr_service_s.max())
    put("BGFailMax", bgr.failed_requests.max(), "{:.0f}")
    dm = v[(v.scenario == "config-drift") & (v.sync_policy == "manual") & (v.trigger_cause == "analysis")]
    put("DriftManAbort", dm.rollback_trigger_latency_s.mean())
    put("SkewMax", v.max_clock_skew_ms.max())
    put("SkewMedian", v.max_clock_skew_ms.median())
    put("DriftAutoBG", v[(v.scenario == "config-drift") & (v.sync_policy == "auto")
                         & (v.strategy == "bluegreen")].mttr_full_s.mean())
    put("NPrecMiss", int((pm["precision met"].astype(str) == "False").sum()), "{:d}")
    fr = core[core.scenario == "faulty-release"]
    put("SensFiveMin", fr.mttr_full_s.mean() - fr.comp_operator_wait_s.mean() + 300, "{:.0f}")
    hl = v[v.scenario.str.startswith("cp-rollouts-prometheus-healthy")]
    put("NFalseRevert", int(((hl.coverage_class == "tolerated")
                             & hl.recovered_by.astype(str).str.contains("operator")).sum()), "{:d}")

    with open(os.path.join(OUT, "numbers.tex"), "w") as f:
        f.write("% generated by scripts/make_tables.py from v2/results/main -- do not edit\n")
        for k in sorted(N):
            f.write("\\newcommand{\\m%s}{%s}\n" % (k, N[k]))
    print("wrote %d macros and 3 tables from %d valid trials" % (len(N), len(v)), file=sys.stderr)


if __name__ == "__main__":
    main()
